"""Split the flat IVCNZ pothole dataset into a YOLOv8 train/val layout.

Input : dataset/raw/Pothole Dataset/{img-N.jpg, img-N.txt}
Output: dataset/pothole/{images,labels}/{train,val}/  +  data.yaml
"""
import random
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw" / "Pothole Dataset"
OUT = HERE / "pothole"
VAL_FRACTION = 0.2
SEED = 42


def main() -> None:
    imgs = sorted(RAW.glob("img-*.jpg"))
    # Keep only images that have a matching, non-empty label (drop unlabeled).
    pairs = []
    for img in imgs:
        lbl = img.with_suffix(".txt")
        if lbl.exists():
            pairs.append((img, lbl))
    if not pairs:
        raise SystemExit(f"No image/label pairs found under {RAW}")

    random.Random(SEED).shuffle(pairs)
    n_val = max(1, int(len(pairs) * VAL_FRACTION))
    val = pairs[:n_val]
    train = pairs[n_val:]

    # Fresh output tree
    if OUT.exists():
        shutil.rmtree(OUT)
    for split in ("train", "val"):
        (OUT / "images" / split).mkdir(parents=True, exist_ok=True)
        (OUT / "labels" / split).mkdir(parents=True, exist_ok=True)

    def place(pairs, split):
        for img, lbl in pairs:
            shutil.copy2(img, OUT / "images" / split / img.name)
            shutil.copy2(lbl, OUT / "labels" / split / lbl.name)

    place(train, "train")
    place(val, "val")

    yaml = OUT / "data.yaml"
    yaml.write_text(
        "# Auto-generated by dataset/prepare.py (IVCNZ pothole dataset)\n"
        f"path: {OUT.as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "nc: 1\n"
        "names: ['pothole']\n",
        encoding="utf-8",
    )

    print(f"train={len(train)} val={len(val)} total={len(pairs)}")
    print(f"data.yaml -> {yaml}")


if __name__ == "__main__":
    main()
